def _read_patch_table(f: BinaryIO, offset: int) -> tuple[tuple[int, tuple[int, ...], int], ...]:
    f.seek(offset)
    rows = []
    for _ in range(17):
        layer, *floors, area = struct.unpack("<6i", f.read(24))
        rows.append((layer, tuple(x for x in floors if x != -1), area))
    return tuple(rows)


def verify_dump(path: Path) -> None:
    """用本机 exe 内存转储核对上面的常量；不一致时抛出 ValueError。"""
    with path.open("rb") as f:
        f.seek(WEAPON_BLOAT_OFFSET)
        got = struct.unpack("<14f", f.read(14 * 4))
        tables = {stage: _read_patch_table(f, offset) for stage, offset in MAP_PATCH_OFFSET.items()}
    if any(abs(a - b) > 1e-4 for a, b in zip(got, WEAPON_BLOAT, strict=True)):
        raise ValueError(f"武器显示倍率与转储不一致：{[round(x, 3) for x in got]}")
    for stage, table in tables.items():
        if table != MAP_PATCHES[stage]:
            raise ValueError(f"st{stage} 的大地图纸片表与转储不一致")
